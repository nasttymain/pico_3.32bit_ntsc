        inline void __put_mb_character(uint32_t code_point, int16_t px, int16_t py){
            // Nothing here :(
        }
    #else
        inline void __put_mb_character(uint32_t code_point, int16_t px, int16_t py);
    #endif
    
    void mes(const char* s, int mode_switch = 0){
        auto px = ::ginfo_cx;
        auto py = ::ginfo_cy;
        ::ginfo_mesx = 0;
        ::ginfo_mesy = fontsize_y;
        unsigned char prevc = 0;
        unsigned char c = 0;
        mbbufi = 0;
        while(*s != '\0'){
            prevc = c;
            c = (unsigned char)(*s);
            if(c >= 32 && c <= 127){
                put_char_graphic( &(font[(c - 32) << 3]) , px, py);
                px += fontsize_x;
            }else if(c < 32){
                // ascii 制御文字
                if(c == 13){
                    // CR
                    if(::ginfo_mesx < (px - ::ginfo_cx)){
                        ::ginfo_mesx = px - ::ginfo_cx;
                    }
                    px = ::ginfo_cx;
                }else if(c == 10){
                    // LF
                    if(prevc != 13 && do_auto_cr == 1){
                        if(::ginfo_mesx < (px - ::ginfo_cx)){
                            ::ginfo_mesx = px - ::ginfo_cx;
                        }
                        px = ::ginfo_cx;
                    }
                    py += fontsize_y;
                }else if(c == 8){
                    // BS
                    px -= fontsize_x;
                }else if(c == 9){
                    px += fontsize_x * hori_tab_size;
                }
            }else{
                // UTF-8
                mbbuf[mbbufi] = c;
                mbbufi += 1;
                if( (mbbuf[0] >> 5) == 0b110 && mbbufi == 2){
                    // 2バイト文字
                    const uint32_t cp = ((mbbuf[0] & 0x1F) << 6) + (mbbuf[1] & 0x3F);
                    __put_mb_character(cp, px, py);
                    mbbufi = 0;
                    px += fontsize_x;
                }else if( (mbbuf[0] >> 4) == 0b1110 && mbbufi == 3){
                    // 3バイト文字
                    const uint32_t cp = ((mbbuf[0] & 0x0F) << 12) + ((mbbuf[1] & 0x3F) << 6) + (mbbuf[2] & 0x3F);
                    __put_mb_character(cp, px, py);
                    mbbufi = 0;
                    px += fontsize_x;
                }else if(mbbufi == 4){
                    // 4バイト文字のつもり
                    // いつかどこかで
                    mbbufi = 0;
                    px += fontsize_x;
                }
            }
            s += 1;
        }
        
        if(::ginfo_mesx < (px - ::ginfo_cx)){
            ::ginfo_mesx = px - ::ginfo_cx;
        }
        ::ginfo_mesy = py - ::ginfo_cy;
        
        if(mode_switch & 1){
            ::ginfo_cx = px;
            ::ginfo_cy = py;
        }else{
            // ::ginfo_cx は当初ので据え置き
            ::ginfo_cy = py + fontsize_y;
        }
    }

