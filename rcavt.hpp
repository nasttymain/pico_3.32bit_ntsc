    // 現在の描画先ポジション。単位は文字(つまり1で8ピクセル)
    int16_t cpos = 0;

    //
    uint16_t CCOLUMNS = _display_size_x / 8;

    void put_char_graphic(char c, int16_t xpos, int16_t ypos){
        const uint8_t code = (uint8_t)(c) - 32;
        for(int16_t x = 0; x < 8; x++){
            const uint8_t row = font[code * 8 + x];
            for(int16_t y = 0; y < 8; y++){
                if(row & static_cast<uint8_t>(0x01 << y)){
                    pset(xpos + x, ypos + y);
                }
            }
        }
    }
    
    // ascii文字を1つ描画
    void putc(char c){
        CCOLUMNS = _display_size_x / 8;
        if(c < 32 || c == 127){
            if(c == 13){
                // CR
                cpos = cpos - (cpos % CCOLUMNS);
            }else if(c == 10){
                // LF
                cpos += CCOLUMNS;
            }else if(c == 9){
                // HT
                cpos = cpos - (cpos % 4) + 4;
            }
            return;
        }
        const int16_t base_x = (cpos % CCOLUMNS) * 8;
        const int16_t base_y = (cpos / CCOLUMNS) * 8;

        put_char_graphic(c, base_x, base_y);
        cpos += 1;

        return;
    }

    void vtputc(char c){
        // あとでなんとかする
    }

    int puts(const char* s){
        int16_t i = 0;
        while(s[i] != 0){
            putc(s[i]);
            i += 1;
        }
        return i;
    }

    void pos(int8_t x, int8_t y){
        cpos = x + y * CCOLUMNS;
        return;
    }
